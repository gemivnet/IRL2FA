#!/usr/bin/env python3
"""Battery-life estimate from hardware/power/model.json.

    python3 hardware/power/power.py            # summary
    python3 hardware/power/power.py --markdown # docs/power-calculations.md body

SPDX-License-Identifier: CERN-OHL-S-2.0
"""
import argparse
import json
from pathlib import Path

MODEL = json.loads((Path(__file__).with_name("model.json")).read_text())
H_PER_YEAR = 24 * 365


def sleep_uA(case):
    return sum(v[case] for v in MODEL["sleep_uA"].values())


def per_use_mAs(case):
    a = MODEL["awake"]
    mcu = a["mcu_mA"][case] * a["awake_s_per_use"]
    epd = a["epd_mA"][case] * (a["full_refresh_s"] * a["full_refreshes_per_use"] +
                              a["fast_refresh_s"] * a["fast_refreshes_per_use"])
    return mcu + epd


def per_year_mAh(profile, case):
    p = MODEL["usage_profiles"][profile]
    a = MODEL["awake"]
    sleep = sleep_uA(case) / 1000 * H_PER_YEAR
    use = per_use_mAs(case) * p["uses_per_day"] * 365 / 3600
    pair = (a["ir_mA"][case] + a["mcu_mA"][case]) * a["pairing_s"] * p["pairings_per_year"] / 3600
    return {"sleep": sleep, "use": use, "pairing": pair, "total": sleep + use + pair}


def life_years(profile, case):
    b = MODEL["battery"]
    per_year = per_year_mAh(profile, case)["total"]
    per_year += b["usable_mAh"] * b["self_discharge_pct_per_year"] / 100
    return b["usable_mAh"] / per_year


def markdown():
    b = MODEL["battery"]
    out = ["# Power calculations", "",
           "_Generated by `hardware/power/power.py` from `hardware/power/model.json`; "
           "CI fails if the worst case drops below "
           f"{MODEL['requirement_years']:g} year._", "",
           f"Battery: **{b['part']}**, {b['usable_mAh']} mAh usable ({b['nominal_mAh']} mAh nominal), "
           f"{b['self_discharge_pct_per_year']} %/year self-discharge.", "",
           "## Sleep current", "", "| Contributor | Typical (µA) | Worst (µA) | Source |", "|-|-|-|-|"]
    for k, v in MODEL["sleep_uA"].items():
        out.append(f"| {k} | {v['typ']:.2f} | {v['worst']:.2f} | {v['source']} |")
    out.append(f"| **Total** | **{sleep_uA('typ'):.2f}** | **{sleep_uA('worst'):.2f}** | |")
    a = MODEL["awake"]
    out += ["", "## One use", "",
            f"Wake, look at a code or the words, sleep: {a['awake_s_per_use']} s awake, "
            f"{a['full_refreshes_per_use']} full refreshes ({a['full_refresh_s']} s each: wake + "
            f"the sleep screen) and {a['fast_refreshes_per_use']} fast refreshes "
            f"({a['fast_refresh_s']} s).", "",
            f"Charge per use: **{per_use_mAs('typ'):.1f} mA·s** typical, "
            f"{per_use_mAs('worst'):.1f} mA·s worst case.", "",
            "## Battery life", "",
            "| Profile | Uses/day | Typical: mAh/year | Typical: years | Worst: mAh/year | Worst: years |",
            "|-|-|-|-|-|-|"]
    for name, p in MODEL["usage_profiles"].items():
        t, w = per_year_mAh(name, "typ"), per_year_mAh(name, "worst")
        out.append(f"| {name} | {p['uses_per_day']} | {t['total']:.0f} | {life_years(name, 'typ'):.1f} | "
                   f"{w['total']:.0f} | {life_years(name, 'worst'):.1f} |")
    out += ["", "Battery life is capped in practice by the cell's shelf life (about 10 years) "
            "and by the e-paper's 0 °C lower limit in cold pockets, not by the electronics.", "",
            "Peak current is the other limit: a coin cell's internal resistance rises as it "
            "empties. `hardware/spice/battery_pulse.cir` checks that a refresh still works with a "
            "half-used cell (40 Ω), and the firmware shows the battery level from VREFINT."]
    return "\n".join(out) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--markdown", action="store_true")
    a = ap.parse_args()
    if a.markdown:
        print(markdown(), end="")
        return
    for name in MODEL["usage_profiles"]:
        print(f"{name:7s} typical {life_years(name, 'typ'):5.1f} y   worst {life_years(name, 'worst'):5.1f} y")


if __name__ == "__main__":
    main()
