#!/usr/bin/env python3
"""Writes docs/bill-of-materials.md from hardware/fab/irl2fa-bom.csv.

Prices and stock come from LCSC and are cached in hardware/bom_prices.json
with the date they were fetched, so the document is reproducible offline:

    python3 hardware/tools/bom_doc.py --refresh   # query LCSC, update the cache
    python3 hardware/tools/bom_doc.py             # regenerate the doc from the cache

SPDX-License-Identifier: CERN-OHL-S-2.0
"""
import argparse
import csv
import datetime
import json
import urllib.request
from pathlib import Path

import yaml

HW = Path(__file__).resolve().parents[1]
BOM = HW / "fab" / "irl2fa-bom.csv"
CACHE = HW / "bom_prices.json"
DOC = HW.parent / "docs" / "bill-of-materials.md"
API = "https://wmsc.lcsc.com/ftps/wm/product/detail?productCode={}"
BOARD = yaml.safe_load((HW / "board.yaml").read_text())["board"]

# Parts bought outside LCSC/JLCPCB (hand-fitted or optional).
EXTRA = [
    {"item": "E-paper display, Good Display GDEY0213B74 (or GDEM0213B74WT for -25 °C)", "qty": 1,
     "unit": 4.95, "where": "[Good Display](https://www.good-display.com/product/391.html)"},
    {"item": "CR2450 lithium coin cell", "qty": 1, "unit": 1.00, "where": "any shop"},
    {"item": "M2 × 6 mm screws, thread-forming for plastic (or M2 machine screws + heat-set inserts)",
     "qty": 4, "unit": 0.05, "where": "any hardware supplier"},
    {"item": "Double-sided adhesive for the display, 0.2 mm (e.g. 3M 467MP), ~60 × 30 mm", "qty": 1,
     "unit": 0.30, "where": "any electronics supplier"},
    {"item": "PETG or PLA filament for the case, ~11 g", "qty": 1, "unit": 0.30, "where": "-"},
]


def fetch(code):
    req = urllib.request.Request(API.format(code), headers={"User-Agent": "Mozilla/5.0 irl2fa-bom"})
    with urllib.request.urlopen(req, timeout=30) as r:
        d = json.load(r)["result"]
    return {
        "mpn": d.get("productModel"),
        "stock": d.get("stockNumber"),
        "breaks": [[int(p["ladder"]), float(p["productPrice"])] for p in d.get("productPriceList", [])],
        "datasheet": d.get("pdfUrl") or "",
    }


def price_at(breaks, qty):
    """Unit price for buying `qty` pieces (respecting the minimum order)."""
    if not breaks:
        return None
    best = breaks[0][1]
    for ladder, price in breaks:
        if qty >= ladder:
            best = price
    return best


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--refresh", action="store_true")
    a = ap.parse_args()
    rows = list(csv.DictReader(BOM.open()))
    cache = json.loads(CACHE.read_text()) if CACHE.exists() else {"fetched": None, "parts": {}}
    if a.refresh:
        for r in rows:
            cache["parts"][r["LCSC"]] = fetch(r["LCSC"])
        cache["fetched"] = datetime.date.today().isoformat()
        CACHE.write_text(json.dumps(cache, indent=1, sort_keys=True) + "\n")

    out = ["# Bill of materials", "",
           "_Generated by `hardware/tools/bom_doc.py` from `hardware/fab/irl2fa-bom.csv`. "
           f"Prices and stock: LCSC, fetched {cache['fetched']}._", "",
           "## Assembled by JLCPCB (or hand-soldered)", "",
           "Unit prices are per board: the \"×1 kit\" column assumes you buy one board's worth "
           "(LCSC's minimum order applies), \"×100\" is the per-board price at 100 boards. "
           "Stock is LCSC's; JLCPCB keeps its own inventory for assembly, so a part out of stock at "
           "LCSC (common for Basic parts such as the 0402 resistors) is usually still available "
           "to JLCPCB's assembly service.", "",
           "| Qty | Refs | Part | Manufacturer | MPN | LCSC | Stock | Unit ×1 kit | Unit ×100 | Line ×100 |",
           "|-|-|-|-|-|-|-|-|-|-|"]
    t1 = t100 = 0.0
    for r in rows:
        q = int(r["Quantity"])
        info = cache["parts"].get(r["LCSC"], {})
        br = info.get("breaks", [])
        p1, p100 = price_at(br, q), price_at(br, q * 100)
        if p1 is not None:
            moq = br[0][0] if br else 1
            t1 += p1 * max(q, moq)
            t100 += p100 * q
        lcsc = f"[{r['LCSC']}](https://www.lcsc.com/product-detail/{r['LCSC']}.html)"
        mpn = r["MPN"]
        if info.get("datasheet"):
            mpn = f"[{mpn}]({info['datasheet']})"
        fmt = lambda v: "?" if v is None else f"${v:.4f}".rstrip("0").rstrip(".")
        out.append(f"| {q} | {r['References']} | {r['Description']} | {r['Manufacturer']} | {mpn} | "
                   f"{lcsc} | {info.get('stock', '?')} | {fmt(p1)} | {fmt(p100)} | "
                   f"{'?' if p100 is None else f'${p100 * q:.3f}'} |")
    out += ["", f"**Electronics, one kit (minimum-order quantities, so you get spares):** ${t1:.2f}  ",
            f"**Electronics per board at 100 boards:** ${t100:.2f}", "",
            "Not in the table, but on the board: the Tag-Connect TC2030 pads (J3, no part: the cable "
            "presses onto the pads), the test points TP1/TP2 and the mounting holes.", "",
            "## Bought separately", "", "| Item | Qty | Unit | Where |", "|-|-|-|-|"]
    te = 0.0
    for e in EXTRA:
        out.append(f"| {e['item']} | {e['qty']} | ${e['unit']:.2f} | {e['where']} |")
        te += e["qty"] * e["unit"]
    out += ["", f"**Separately bought parts per device:** about ${te:.2f}", "",
            "## PCB and assembly", "",
            f"- 2-layer, {BOARD['width']:g} × {BOARD['height']:g} mm, {BOARD['thickness']:g} mm thick, "
            "any colour. JLCPCB's minimum order is 5 boards, typically about $2-5 for the bare boards "
            "plus shipping.",
            "- Choose the **ENIG** surface finish: a bare pad under the coin cell is its negative "
            "contact, and gold makes a lasting contact where HASL tin can oxidise.",
            "- Assembly uses both sides: the joystick is on the front, everything else on the back. "
            "JLCPCB's Standard PCBA does both sides. Upload `hardware/fab/irl2fa-gerbers.zip`, "
            "`irl2fa-bom-jlcpcb.csv` and `irl2fa-cpl-jlcpcb.csv`.",
            "- The STM32U083 is often low in LCSC stock. JLCPCB's global sourcing or a consigned "
            "part from DigiKey/Mouser works, and the STM32U073KCU6 is pin-compatible "
            "(no AES, which the firmware doesn't need).",
            "- Extended parts carry a one-off JLCPCB setup fee each (about $3 per unique part).", "",
            "See [hardware-options.md](hardware-options.md) for why each part was chosen and the "
            "alternatives."]
    DOC.write_text("\n".join(out) + "\n")
    print("wrote", DOC)


if __name__ == "__main__":
    main()
