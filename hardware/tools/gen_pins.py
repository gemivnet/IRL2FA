#!/usr/bin/env python3
"""Generate firmware/port/stm32u0/pins.h (and, with --docs, docs/pin-assignments.md)
from hardware/pins.yaml, the single source of truth for the MCU pin-out.

    python3 hardware/tools/gen_pins.py            # writes pins.h
    python3 hardware/tools/gen_pins.py --docs     # writes pins.h and the docs table
    python3 hardware/tools/gen_pins.py --check    # exit 1 if either file is stale

SPDX-License-Identifier: AGPL-3.0-or-later
"""
import argparse
import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]
PINS_YAML = ROOT / "hardware" / "pins.yaml"
PINS_H = ROOT / "firmware" / "port" / "stm32u0" / "pins.h"
DOCS_MD = ROOT / "docs" / "pin-assignments.md"

GPIO_RE = re.compile(r"^P([A-F])(\d{1,2})$")
MODES = {"input", "input_pullup", "output", "af"}
DIRECTIONS = {"up": "BTN_UP", "down": "BTN_DOWN", "left": "BTN_LEFT",
              "right": "BTN_RIGHT", "center": "BTN_CENTER"}
# Pins the port must never reconfigure: SWD (debug access) and the dedicated
# NRST / BOOT0 functions.
RESERVED_NETS = {"SWDIO", "SWCLK", "NRST", "BOOT0"}


class PinError(Exception):
    pass


def load(path=PINS_YAML):
    data = yaml.safe_load(path.read_text())
    pins = data.get("pins") or []
    seen_pin, seen_sym, seen_gpio = set(), set(), set()
    out = []
    for p in pins:
        num, name, net = p.get("pin"), str(p.get("name")), p.get("net")
        if num in seen_pin:
            raise PinError(f"package pin {num} listed twice")
        seen_pin.add(num)
        m = GPIO_RE.match(name)
        mode = p.get("mode")
        sym = p.get("symbol")
        if mode is not None and mode not in MODES:
            raise PinError(f"pin {num} {name}: unknown mode {mode!r}")
        if mode == "af" and not isinstance(p.get("af"), int):
            raise PinError(f"pin {num} {name}: mode af needs an integer af number")
        if sym is not None:
            if not re.match(r"^[A-Z][A-Z0-9_]*$", sym):
                raise PinError(f"pin {num}: symbol {sym!r} is not a C identifier")
            if sym in seen_sym:
                raise PinError(f"symbol {sym} used twice")
            seen_sym.add(sym)
            if not m:
                raise PinError(f"pin {num} {name}: only GPIOs can carry a symbol")
            if mode is None:
                raise PinError(f"pin {num} {name}: symbol {sym} without a mode")
        if m:
            if name in seen_gpio:
                raise PinError(f"{name} listed twice")
            seen_gpio.add(name)
        if p.get("exti") and mode not in ("input", "input_pullup"):
            raise PinError(f"pin {num} {name}: exti on a non-input pin")
        out.append({
            "pin": num, "name": name, "net": net, "mode": mode, "af": p.get("af"),
            "exti": bool(p.get("exti")), "symbol": sym, "notes": p.get("notes") or "",
            "port": m.group(1) if m else None, "num": int(m.group(2)) if m else None,
        })
    # EXTI lines are shared between ports: two EXTI pins with the same number
    # cannot both wake the device.
    lines = {}
    for p in out:
        if p["exti"]:
            if p["num"] in lines:
                raise PinError(f"EXTI line {p['num']} used by both {lines[p['num']]} and {p['name']}")
            lines[p["num"]] = p["name"]
    joy = data.get("joystick") or {}
    for net, d in joy.items():
        if d not in DIRECTIONS:
            raise PinError(f"joystick {net}: unknown direction {d!r}")
        if net not in seen_sym:
            raise PinError(f"joystick {net}: no pin has that symbol")
    if sorted(joy.values()) != sorted(DIRECTIONS):
        raise PinError("joystick: every direction must be mapped exactly once")
    return data, out, joy


def function_of(p):
    if p["port"] is None:
        if p["net"] in ("GND",):
            return "ground"
        if p["name"].startswith("VDD") or p["name"].startswith("VSS"):
            return "power"
        return "-"
    if p["net"] in RESERVED_NETS:
        return {"SWDIO": "SWD (AF0)", "SWCLK": "SWD (AF0)", "NRST": "reset",
                "BOOT0": "boot select"}[p["net"]]
    if p["mode"] is None:
        return "unused (analog)"
    f = {"input": "GPIO input", "input_pullup": "GPIO input, pull-up",
         "output": "GPIO output", "af": f"AF{p['af']}"}[p["mode"]]
    if p["exti"]:
        f += ", EXTI wake"
    return f


def gen_header(data, pins, joy):
    L = []
    w = L.append
    w("/* GENERATED by hardware/tools/gen_pins.py from hardware/pins.yaml.")
    w(" * Do not edit: change pins.yaml and re-run the generator.")
    w(" * SPDX-License-Identifier: AGPL-3.0-or-later */")
    w("#ifndef IRL2FA_PINS_H")
    w("#define IRL2FA_PINS_H")
    w("")
    w(f"/* MCU {data.get('mcu')} ({data.get('package')}) */")
    w("")
    w("/* Per signal: _PORT (GPIO_TypeDef *), _NUM (0..15), _MASK (1 << _NUM, the")
    w(" * same value as the LL_GPIO_PIN_x constants), _MODE and, for AF pins, _AF. */")
    w("#define PIN_MODE_INPUT 0")
    w("#define PIN_MODE_INPUT_PULLUP 1")
    w("#define PIN_MODE_OUTPUT 2")
    w("#define PIN_MODE_AF 3")
    w("")
    mode_c = {"input": "PIN_MODE_INPUT", "input_pullup": "PIN_MODE_INPUT_PULLUP",
              "output": "PIN_MODE_OUTPUT", "af": "PIN_MODE_AF"}
    for p in pins:
        if not p["symbol"]:
            continue
        s = "PIN_" + p["symbol"]
        w(f"/* package pin {p['pin']}, {p['name']}, net {p['net']}: {p['notes']} */")
        w(f"#define {s}_PORT GPIO{p['port']}")
        w(f"#define {s}_NUM {p['num']}u")
        w(f"#define {s}_MASK (1u << {p['num']})")
        w(f"#define {s}_MODE {mode_c[p['mode']]}")
        if p["mode"] == "af":
            w(f"#define {s}_AF {p['af']}u")
        if p["exti"]:
            w(f"#define {s}_EXTI 1")
        w("")
    # Per-port masks.
    ports = sorted({p["port"] for p in pins if p["port"]})
    w("/* Per port: pins present on the package, pins the firmware configures, and")
    w(" * pins that must be left alone (SWD, NRST, BOOT0). Everything else is put")
    w(" * in analog mode for the lowest leakage. */")
    for port in ports:
        present = used = reserved = 0
        for p in pins:
            if p["port"] != port:
                continue
            present |= 1 << p["num"]
            if p["mode"] is not None and p["net"] not in RESERVED_NETS:
                used |= 1 << p["num"]
            if p["net"] in RESERVED_NETS:
                reserved |= 1 << p["num"]
        w(f"#define PINS_GPIO{port}_PRESENT 0x{present:04X}u")
        w(f"#define PINS_GPIO{port}_USED 0x{used:04X}u")
        w(f"#define PINS_GPIO{port}_RESERVED 0x{reserved:04X}u")
        w(f"#define PINS_GPIO{port}_ANALOG 0x{present & ~used & ~reserved & 0xFFFF:04X}u")
    w("")
    exti = [p for p in pins if p["exti"]]
    mask = 0
    for p in exti:
        mask |= 1 << p["num"]
    w("/* EXTI lines used as wake-up sources (falling edge). */")
    w(f"#define PINS_EXTI_MASK 0x{mask:04X}u")
    w("")
    w("/* Joystick: which pin is which direction (pins.yaml `joystick:`). */")
    inv = {d: net for net, d in joy.items()}
    for d in ("up", "down", "left", "right", "center"):
        w(f"#define JOY_{d.upper()} PIN_{inv[d]}")
    w("#define JOY_FOR_EACH(X) \\")
    items = [f"X(JOY_{d.upper()}, {DIRECTIONS[d]})" for d in ("up", "down", "left", "right", "center")]
    w("    " + " \\\n    ".join(items))
    w("")
    w("#endif")
    return "\n".join(L) + "\n"


def md_escape(s):
    return str(s).replace("|", "\\|")


def gen_docs(data, pins, joy):
    L = []
    w = L.append
    w("# Pin assignments")
    w("")
    w("<!-- GENERATED by hardware/tools/gen_pins.py --docs from hardware/pins.yaml. Do not edit. -->")
    w("")
    w(f"MCU: **{data.get('mcu')}**, package {data.get('package')}. The firmware uses these")
    w("assignments through the generated `firmware/port/stm32u0/pins.h`; unused GPIOs are")
    w("configured as analog inputs for the lowest leakage.")
    w("")
    w("| Pin | Name | Net | Function | Notes |")
    w("|-:|-|-|-|-|")
    for p in sorted(pins, key=lambda p: (p["pin"] if isinstance(p["pin"], int) else 999)):
        net = p["net"] if p["net"] else "-"
        w(f"| {p['pin']} | {p['name']} | {md_escape(net)} | {md_escape(function_of(p))} | {md_escape(p['notes'])} |")
    w("")
    w("## Joystick directions")
    w("")
    w("The five-way switch sits at 45 degrees on the board; seen from the front with the")
    w("screen upright the contacts map to:")
    w("")
    w("| Direction | Net | MCU pin |")
    w("|-|-|-|")
    by_sym = {p["symbol"]: p for p in pins if p["symbol"]}
    for d in ("up", "right", "down", "left", "center"):
        net = next(n for n, v in joy.items() if v == d)
        p = by_sym[net]
        w(f"| {d} | {net} | {p['name']} (pin {p['pin']}) |")
    w("")
    return "\n".join(L)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--docs", action="store_true", help="also write docs/pin-assignments.md")
    ap.add_argument("--check", action="store_true", help="do not write; fail if outputs are stale")
    ap.add_argument("--yaml", type=Path, default=PINS_YAML)
    ap.add_argument("--header", type=Path, default=PINS_H)
    ap.add_argument("--docs-out", type=Path, default=DOCS_MD)
    a = ap.parse_args(argv)
    try:
        data, pins, joy = load(a.yaml)
    except PinError as e:
        print(f"pins.yaml: {e}", file=sys.stderr)
        return 2
    outputs = [(a.header, gen_header(data, pins, joy))]
    if a.docs or a.check:
        outputs.append((a.docs_out, gen_docs(data, pins, joy)))
    stale = False
    for path, text in outputs:
        if a.check:
            if not path.exists() or path.read_text() != text:
                print(f"stale: {path}", file=sys.stderr)
                stale = True
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
            print(f"wrote {path.relative_to(ROOT) if path.is_relative_to(ROOT) else path}")
    return 1 if stale else 0


if __name__ == "__main__":
    sys.exit(main())
