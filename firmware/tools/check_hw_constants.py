#!/usr/bin/env python3
"""Checks every hand-written STM32U083 address, offset, bit and IRQ number in
the repository against ST's CMSIS device header (the vendored
firmware/port/stm32u0/vendor/cmsis_device_u0/stm32u083xx.h, STM32CubeU0
v1.3.0, Apache-2.0), which is generated by ST from the same register
database as RM0503.

The firmware itself takes its registers from that header, so what can drift
from the silicon is everything written by hand around it:

  * the Renode platform (firmware/renode/stm32u083.repl): peripheral base
    addresses, IRQ numbers, tagged regions;
  * the Renode models (U0Map in firmware/renode/models/STM32U0_System.cs):
    every register offset and bit they emulate. A model that disagrees
    with the silicon would hide a firmware bug instead of catching it;
  * the vector table in startup_stm32u083.c, against IRQn_Type;
  * the flash map (port/stm32u0/flash_layout.ld, flash_layout.h, the two
    linker scripts and tools/sign_image.py): against the header's memory
    map, and against each other.

The header is compiled with the host C compiler and the values printed, so
macro arithmetic and struct layout (offsetof) are evaluated exactly as the
firmware build sees them. Exit status 1 on any mismatch.

SPDX-License-Identifier: AGPL-3.0-or-later
"""
from __future__ import annotations

import os
import re
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
PORT = ROOT / "firmware/port/stm32u0"
VENDOR = PORT / "vendor"
REPL = ROOT / "firmware/renode/stm32u083.repl"
MODELS = ROOT / "firmware/renode/models/STM32U0_System.cs"
STARTUP = PORT / "startup_stm32u083.c"
LINKER = PORT / "stm32u083kc.ld"
BOOT_LINKER = PORT / "boot/boot.ld"
LAYOUT_LD = PORT / "flash_layout.ld"
LAYOUT_H = PORT / "flash_layout.h"
SIGN_TOOL = ROOT / "firmware/tools/sign_image.py"

# Renode peripheral name in the .repl -> CMSIS base address macro.
REPL_BASES = {
    "flash": "FLASH_BASE", "sram": "SRAM1_BASE", "rcc": "RCC_BASE", "pwr": "PWR_BASE",
    "flash_ctrl": "FLASH_R_BASE", "exti": "EXTI_BASE", "rng": "RNG_BASE", "adc": "ADC1_BASE",
    "gpioPortA": "GPIOA_BASE", "gpioPortB": "GPIOB_BASE", "gpioPortC": "GPIOC_BASE",
    "gpioPortF": "GPIOF_BASE", "usart1": "USART1_BASE", "i2c1": "I2C1_BASE", "spi1": "SPI1_BASE",
    "nvic": None,  # Cortex-M core, not in the device header
}
# Renode peripheral -> CMSIS IRQn names of its NVIC lines, in output order.
REPL_IRQS = {
    "usart1": ["USART1_IRQn"], "i2c1": ["I2C1_IRQn", "I2C1_IRQn"], "spi1": ["SPI1_IRQn"],
    "exti": ["EXTI0_1_IRQn", "EXTI2_3_IRQn", "EXTI4_15_IRQn"],
}
# Sizes the repl gives memories: name -> C expression in the header's terms.
REPL_SIZES = {
    "flash": "FLASH_SIZE_DEFAULT",
    "sram": "(SRAM1_SIZE_MAX + 0x2000UL)",  # SRAM1 32 KB + SRAM2 8 KB (RM0503 Table 5)
}


def fail(msg: str, errors: list[str]) -> None:
    errors.append(msg)


def c_number(text: str) -> int:
    """Evaluates a C#/C integer literal expression such as `0x7Fu << 3`."""
    expr = re.sub(r"(?<=[0-9A-Fa-f])[uUlL]+\b", "", text.strip())
    if not re.fullmatch(r"[0-9A-Fa-fxX\s<>|&()+\-~*]+", expr):
        raise ValueError(f"not a plain integer expression: {text!r}")
    return eval(expr, {"__builtins__": {}}) & 0xFFFFFFFFFFFFFFFF  # noqa: S307 (validated above)


def parse_repl() -> tuple[dict[str, int], dict[str, list[int]], dict[str, int], list[tuple[str, int]]]:
    bases, irqs, sizes, tags = {}, {}, {}, []
    current = None
    for line in REPL.read_text().splitlines():
        line = line.split("//")[0].rstrip()
        m = re.match(r"^(\w+):\s*[\w.]+\s*@\s*\{?\s*sysbus\s*(?:<\s*)?(0x[0-9A-Fa-f]+)", line)
        if m:
            current = m.group(1)
            bases[current] = int(m.group(2), 16)
            continue
        m = re.match(r"^(\w+):", line)
        if m:
            current = m.group(1)
            continue
        if current is None:
            continue
        m = re.match(r"^\s+size:\s*(0x[0-9A-Fa-f]+)", line)
        if m:
            sizes[current] = int(m.group(1), 16)
        m = re.match(r"^\s+(?:\[(\d+)-(\d+)\]|\w+)\s*->\s*nvic@\[?(\d+)(?:-(\d+))?\]?", line)
        if m:
            if m.group(4):
                irqs.setdefault(current, []).extend(range(int(m.group(3)), int(m.group(4)) + 1))
            else:
                irqs.setdefault(current, []).append(int(m.group(3)))
        m = re.match(r'^\s+Tag\s*<\s*(0x[0-9A-Fa-f]+)\s*,\s*0x[0-9A-Fa-f]+\s*>\s*"(\w+)"', line)
        if m:
            tags.append((m.group(2), int(m.group(1), 16)))
    return bases, irqs, sizes, tags


def parse_u0map() -> dict[str, int]:
    text = MODELS.read_text()
    m = re.search(r"public static class U0Map\s*\{(.*?)\n    \}", text, re.S)
    if not m:
        raise SystemExit(f"{MODELS}: no U0Map class")
    out = {}
    for name, value in re.findall(r"public const \w+ (\w+)\s*=\s*([^;]+);", m.group(1)):
        out[name] = c_number(value)
    return out


def parse_vectors() -> list[str]:
    text = STARTUP.read_text()
    m = re.search(r"vector_table\[[^\]]*\]\s*=\s*\{(.*?)\};", text, re.S)
    body = re.sub(r"/\*.*?\*/", "", m.group(1), flags=re.S)
    items = [x.strip() for x in body.split(",") if x.strip()]
    return items[16:]  # after the 16 Cortex-M system entries


def parse_irqn() -> dict[str, int]:
    text = (VENDOR / "cmsis_device_u0/stm32u083xx.h").read_text()
    m = re.search(r"typedef enum\s*\{(.*?)\}\s*IRQn_Type;", text, re.S)
    return {n: int(v) for n, v in re.findall(r"(\w+_IRQn)\s*=\s*(-?\d+)", m.group(1))}


def evaluate(exprs: dict[str, str]) -> dict[str, int]:
    """Compiles the header with the host compiler and prints each expression."""
    cc = os.environ.get("CC", "cc")
    lines = ['#include <stdio.h>', '#include <stddef.h>', '#include "stm32u0xx.h"', "int main(void) {"]
    for key, expr in exprs.items():
        lines.append(f'  printf("%s %llu\\n", "{key}", (unsigned long long)({expr}));')
    lines += ["  return 0;", "}"]
    with tempfile.TemporaryDirectory() as tmp:
        src, exe = Path(tmp, "c.c"), Path(tmp, "c")
        src.write_text("\n".join(lines) + "\n")
        cmd = [cc, "-std=c11", "-w", "-DSTM32U083xx", f"-I{VENDOR}/cmsis_device_u0", f"-I{VENDOR}/cmsis_core",
               "-o", str(exe), str(src)]
        r = subprocess.run(cmd, capture_output=True, text=True)
        if r.returncode != 0:
            # Name the expressions that do not compile (unknown macro or member).
            raise SystemExit("compiling against stm32u083xx.h failed:\n" + r.stderr[-4000:])
        out = subprocess.run([str(exe)], capture_output=True, text=True, check=True).stdout
    return {k: int(v) for k, v in (line.split() for line in out.splitlines())}


def u0map_expr(name: str) -> str:
    m = re.fullmatch(r"OFF_([A-Z0-9]+)_(\w+)", name)
    if m:
        periph = {"I2C": "I2C", "SPI": "SPI", "USART": "USART", "GPIO": "GPIO"}.get(m.group(1), m.group(1))
        return f"offsetof({periph}_TypeDef, {m.group(2)})"
    return name


def main() -> int:
    errors: list[str] = []
    checked = 0
    bases, repl_irqs, sizes, tags = parse_repl()
    u0map = parse_u0map()
    vectors = parse_vectors()
    irqn = parse_irqn()

    exprs: dict[str, str] = {}
    for periph, macro in REPL_BASES.items():
        if macro:
            exprs[f"repl:{periph}"] = macro
    for tag, _ in tags:
        exprs[f"tag:{tag}"] = f"{tag}_BASE"
    for name in u0map:
        if name in ("FlashKey1", "FlashKey2", "OptKey1", "OptKey2", "ScbScr", "ScbScrSleepDeep"):
            continue  # not in the device header; see the comments in U0Map
        exprs[f"map:{name}"] = u0map_expr(name)
    for name, expr in REPL_SIZES.items():
        exprs[f"size:{name}"] = expr
    exprs["ld:flash_total"] = "FLASH_SIZE_DEFAULT"
    exprs["ld:sram_base"] = "SRAM1_BASE"
    exprs["ld:sram2_base"] = "BKPSRAM2_BASE"
    exprs["ld:sram1_size"] = "SRAM1_SIZE_MAX"
    exprs["ld:flash_base"] = "FLASH_BASE"
    values = evaluate(exprs)

    # 1. Renode platform: bases, sizes, IRQs, tags.
    for periph, macro in REPL_BASES.items():
        if not macro:
            continue
        checked += 1
        if periph not in bases:
            fail(f"stm32u083.repl: no '{periph}'", errors)
        elif bases[periph] != values[f"repl:{periph}"]:
            fail(f"stm32u083.repl: {periph} @ 0x{bases[periph]:08X}, {macro} = 0x{values[f'repl:{periph}']:08X}", errors)
    for name in REPL_SIZES:
        checked += 1
        if sizes.get(name) != values[f"size:{name}"]:
            fail(f"stm32u083.repl: {name} size 0x{sizes.get(name, 0):X}, expected 0x{values[f'size:{name}']:X}", errors)
    for tag, addr in tags:
        checked += 1
        if addr != values[f"tag:{tag}"]:
            fail(f"stm32u083.repl: Tag {tag} at 0x{addr:08X}, {tag}_BASE = 0x{values[f'tag:{tag}']:08X}", errors)
    for periph, names in REPL_IRQS.items():
        checked += 1
        want = [irqn[n] for n in names]
        if repl_irqs.get(periph) != want:
            fail(f"stm32u083.repl: {periph} IRQ lines {repl_irqs.get(periph)}, header says {want} ({names})", errors)

    # 2. Model constants.
    for name, value in u0map.items():
        key = f"map:{name}"
        if key not in values:
            continue
        checked += 1
        if values[key] != value:
            fail(f"U0Map.{name} = 0x{value:X}, {u0map_expr(name)} = 0x{values[key]:X}", errors)
    # The models must use U0Map, not bare register offsets.
    text = MODELS.read_text()
    body = text.split("public static class U0Map", 1)[1].split("\n    }\n", 1)[1]
    for m in re.finditer(r"case 0x[0-9A-Fa-f]+\s*:", body):
        fail(f"STM32U0_System.cs: bare register offset '{m.group(0)}' outside U0Map", errors)

    # 3. Vector table order against IRQn_Type.
    by_number = {v: k for k, v in irqn.items() if v >= 0}
    for i in range(max(by_number) + 1):
        checked += 1
        want = by_number.get(i)
        have = vectors[i] if i < len(vectors) else None
        if want is None:
            if have not in ("0", None):
                fail(f"vector {i}: '{have}', but IRQn {i} does not exist", errors)
        elif have != want.replace("_IRQn", "_IRQHandler"):
            fail(f"vector {i}: '{have}', IRQn_Type has {want}", errors)
    if len(vectors) != max(by_number) + 1:
        fail(f"vector table has {len(vectors)} device entries, IRQn_Type {max(by_number) + 1}", errors)

    # 4. The flash map: flash_layout.ld against the header, then the C
    # header, the linker scripts and the image tool against it.
    def ld_value(text: str) -> int:
        text = text.strip()
        m = re.fullmatch(r"(\d+)K", text)
        return int(m.group(1)) * 1024 if m else int(text, 0)

    lay = {k: ld_value(v) for k, v in re.findall(r"^(__\w+)\s*=\s*([0-9A-Fa-fxXK]+)\s*;", LAYOUT_LD.read_text(), re.M)}
    base = values["ld:flash_base"]
    regions = [("boot", "__boot_start", "__boot_size"), ("app", "__app_slot_start", "__app_slot_size"),
               ("staging", "__staging_start", "__staging_size"), ("log", "__log_start", "__log_size"),
               ("store", "__store_start", "__store_size")]
    checked += 4
    if lay["__flash_base"] != base or lay["__boot_start"] != base:
        fail("flash_layout.ld: flash does not start at FLASH_BASE", errors)
    at = base
    for name, start, size in regions:
        if lay[start] != at or lay[start] % 2048 or lay[size] % 2048:
            fail(f"flash_layout.ld: {name} is not page-aligned right after the previous region", errors)
        at = lay[start] + lay[size]
    if at != base + values["ld:flash_total"]:
        fail("flash_layout.ld: the regions do not tile the 256 KB main flash", errors)
    if (lay["__ram_start"] != values["ld:sram_base"] or values["ld:sram2_base"] != values["ld:sram_base"] + values["ld:sram1_size"]
            or lay["__ram_size"] != values["ld:sram1_size"] + 0x2000 or lay["__mailbox"] + 16 != lay["__ram_start"] + lay["__ram_size"]):
        fail("flash_layout.ld: RAM is not SRAM1 (32 KB) + SRAM2 (8 KB) at 0x20000000 with the mailbox on top", errors)

    hdefs = {k: int(v, 0) for k, v in re.findall(r"#define (FL_\w+) (0x[0-9A-Fa-f]+|\d+)u", LAYOUT_H.read_text())}
    pairs = {"FL_BOOT_SIZE": "__boot_size", "FL_APP_SIZE": "__app_slot_size", "FL_STAGING_SIZE": "__staging_size",
             "FL_LOG_SIZE": "__log_size", "FL_STORE_SIZE": "__store_size"}
    offs = {"FL_APP_OFF": "__app_slot_start", "FL_STAGING_OFF": "__staging_start", "FL_LOG_OFF": "__log_start",
            "FL_STORE_OFF": "__store_start"}
    for h, l in pairs.items():
        checked += 1
        if hdefs.get(h) != lay[l]:
            fail(f"flash_layout.h {h} != flash_layout.ld {l}", errors)
    for h, l in offs.items():
        checked += 1
        if hdefs.get(h, -1) + base != lay[l]:
            fail(f"flash_layout.h {h} != flash_layout.ld {l}", errors)
    checked += 1
    if hdefs.get("FL_MAILBOX_ADDR") != lay["__mailbox"]:
        fail("flash_layout.h FL_MAILBOX_ADDR != flash_layout.ld __mailbox", errors)
    checked += 1
    if hdefs.get("FL_BOOT_DEBUG_ADDR") != lay["__boot_debug"] or lay["__boot_debug"] + 32 != lay["__mailbox"]:
        fail("flash_layout: the boot debug block is not the 32 bytes below the mailbox", errors)

    tool = SIGN_TOOL.read_text()
    tdefs = {k: int(v, 0) for k, v in re.findall(r"^(\w+) = (0x[0-9A-Fa-f]+)\b", tool, re.M)}
    for t, l in (("BOOT_SIZE", "__boot_size"), ("APP_SIZE", "__app_slot_size"), ("STAGING_SIZE", "__staging_size")):
        checked += 1
        if tdefs.get(t) != lay[l]:
            fail(f"sign_image.py {t} != flash_layout.ld {l}", errors)
    for t, l in (("APP_ADDR", "__app_slot_start"), ("STAGING_ADDR", "__staging_start")):
        checked += 1
        if tdefs.get(t, -1) + base != lay[l]:
            fail(f"sign_image.py {t} != flash_layout.ld {l}", errors)
    checked += 1
    if tdefs.get("HW_ID") != hdefs.get("FL_HW_ID"):
        fail("sign_image.py HW_ID != flash_layout.h FL_HW_ID", errors)

    def memory(path: Path) -> dict[str, int]:
        m = re.search(r"FLASH\s*\(rx\)\s*:\s*ORIGIN\s*=\s*(0x[0-9A-Fa-f]+)\s*,\s*LENGTH\s*=\s*([^\n]+)", path.read_text())
        length = eval(re.sub(r"(\d+)K", r"(\1*1024)", m.group(2)), {"__builtins__": {}})  # noqa: S307 (own file)
        return {"origin": int(m.group(1), 16), "length": length}

    app, boot = memory(LINKER), memory(BOOT_LINKER)
    checked += 2
    if app["origin"] != lay["__app_slot_start"] + lay["__app_offset"] or \
            app["origin"] + app["length"] != lay["__app_slot_start"] + lay["__app_slot_size"]:
        fail("stm32u083kc.ld: FLASH is not the application slot after its 256-byte header", errors)
    if boot["origin"] != lay["__boot_start"] or boot["length"] != lay["__boot_size"]:
        fail("boot/boot.ld: FLASH is not the bootloader region", errors)

    for e in errors:
        print("MISMATCH:", e)
    print(f"check_hw_constants: {checked} values checked against stm32u083xx.h, {len(errors)} mismatches")
    return 1 if errors else 0


if __name__ == "__main__":
    sys.exit(main())
