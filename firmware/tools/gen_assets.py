#!/usr/bin/env python3
"""Generate firmware/core/wordlist.c and firmware/core/fonts.c.

The generated files are committed, so building the firmware never needs this
script; run it only to change the wordlist or the fonts:

    python firmware/tools/gen_assets.py [--font-dir /usr/share/fonts/truetype/dejavu]

Fonts are rasterised from DejaVu Sans / DejaVu Sans Mono (Bitstream Vera
licence, see THIRD_PARTY.md) at fixed pixel heights and stored as 1-bpp
row-major bitmaps.

SPDX-License-Identifier: AGPL-3.0-or-later
"""
import argparse
import hashlib
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
CORE = ROOT / "core"
BIP39 = ROOT / "data" / "bip39-english.txt"
BIP39_SHA256 = "2f5eed53a4727b4bf8880d8f3f199efc90e58503646d9ff8eff3a2ed3b24dbda"

# name, ttf file, pixel size, character set
FONTS = [
    ("font_small", "DejaVuSans.ttf", 11, None),
    ("font_medium", "DejaVuSans-Bold.ttf", 14, None),
    ("font_large", "DejaVuSans-Bold.ttf", 22, None),
    ("font_mono", "DejaVuSansMono-Bold.ttf", 15, None),
    ("font_digits", "DejaVuSansMono-Bold.ttf", 44, "0123456789 "),
]
ASCII = "".join(chr(c) for c in range(32, 127))

HEADER = "/* GENERATED by firmware/tools/gen_assets.py -- do not edit.\n * SPDX-License-Identifier: AGPL-3.0-or-later */\n"


def gen_wordlist():
    data = BIP39.read_bytes()
    if hashlib.sha256(data).hexdigest() != BIP39_SHA256:
        raise SystemExit("bip39-english.txt does not match the canonical list")
    words = data.decode().split()
    assert len(words) == 2048
    blob = "\\0".join(words)
    offsets = []
    pos = 0
    for w in words:
        offsets.append(pos)
        pos += len(w) + 1
    out = [HEADER, '#include "words.h"\n\n',
           "/* BIP-39 English wordlist (MIT), NUL-separated. */\n",
           "static const char WORDS[] =\n"]
    line = ""
    for w in words:
        piece = w + "\\0"
        if len(line) + len(piece) > 90:
            out.append(f'    "{line}"\n')
            line = ""
        line += piece
    out.append(f'    "{line}";\n\n')
    out.append("static const uint16_t OFFSETS[2048] = {\n")
    for i in range(0, 2048, 12):
        out.append("    " + ", ".join(str(o) for o in offsets[i:i + 12]) + ",\n")
    out.append("};\n\n")
    out.append("const char *words_word(uint16_t index)\n{\n"
               "    return &WORDS[OFFSETS[index & 0x7ff]];\n}\n")
    (CORE / "wordlist.c").write_text("".join(out))


def rasterise(ttf, size, chars):
    font = ImageFont.truetype(str(ttf), size)
    ascent, descent = font.getmetrics()
    height = ascent + descent
    glyphs = []
    for ch in chars:
        adv = int(round(font.getlength(ch)))
        w = max(adv, 1)
        img = Image.new("1", (w + 4, height), 0)
        ImageDraw.Draw(img).text((0, 0), ch, font=font, fill=1)
        bbox = img.getbbox()
        # Keep the advance width; crop only columns that are blank beyond it.
        right = max(w, bbox[2] if bbox else 0)
        img = img.crop((0, 0, right, height))
        rows = []
        stride = (right + 7) // 8
        px = img.load()
        for y in range(height):
            row = bytearray(stride)
            for x in range(right):
                if px[x, y]:
                    row[x // 8] |= 0x80 >> (x % 8)
            rows.append(bytes(row))
        glyphs.append((ch, right, adv, b"".join(rows)))
    return height, ascent, glyphs


def gen_fonts(font_dir: Path):
    out = [HEADER, '#include "fonts.h"\n\n']
    for name, ttf, size, chars in FONTS:
        chars = chars or ASCII
        height, ascent, glyphs = rasterise(font_dir / ttf, size, chars)
        bits = bytearray()
        offs, widths, advs = [], [], []
        for _, w, adv, data in glyphs:
            offs.append(len(bits))
            widths.append(w)
            advs.append(adv)
            bits += data
        out.append(f"/* {ttf} {size}px, {len(chars)} glyphs, {len(bits)} bytes */\n")
        out.append(f"static const uint8_t {name}_bits[] = {{\n")
        for i in range(0, len(bits), 16):
            out.append("    " + ", ".join(f"0x{b:02x}" for b in bits[i:i + 16]) + ",\n")
        out.append("};\n")
        out.append(f"static const uint16_t {name}_offsets[] = {{" + ", ".join(map(str, offs)) + "};\n")
        out.append(f"static const uint8_t {name}_widths[] = {{" + ", ".join(map(str, widths)) + "};\n")
        out.append(f"static const uint8_t {name}_advances[] = {{" + ", ".join(map(str, advs)) + "};\n")
        cmap = chars.replace("\\", "\\\\").replace('"', '\\"')
        out.append(f"const font_t {name} = {{\n"
                   f"    .height = {height},\n    .ascent = {ascent},\n"
                   f"    .count = {len(chars)},\n    .chars = \"{cmap}\",\n"
                   f"    .bits = {name}_bits,\n    .offsets = {name}_offsets,\n"
                   f"    .widths = {name}_widths,\n    .advances = {name}_advances,\n}};\n\n")
    (CORE / "fonts.c").write_text("".join(out))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--font-dir", type=Path, default=Path("/usr/share/fonts/truetype/dejavu"))
    args = ap.parse_args()
    gen_wordlist()
    gen_fonts(args.font_dir)
    print("wrote", CORE / "wordlist.c", "and", CORE / "fonts.c")


if __name__ == "__main__":
    main()
