#!/usr/bin/env python3
"""Regenerates firmware/tests/data/fw_fixtures.h: an LZMA stream and a signed
image header made by firmware/tools/sign_image.py, so the C tests check the
device-side decoder and signature check against the host tool's output.

The binary is a deterministic pseudo-firmware (sample_plain() here and in
tests/test_fwupdate.c must stay identical); the image is signed with the
TEST key, the RFC 8032 section 7.1 TEST 1 secret key: public on purpose,
never built into a release bootloader.

    python3 firmware/tests/data/make_fw_fixtures.py
SPDX-License-Identifier: AGPL-3.0-or-later
"""
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parents[1] / "tools"))
import sign_image  # noqa: E402

TEST_SEED = bytes.fromhex("9d61b19deffd5a60ba844af492ec2cc44449c5697b326919703bac031cae7f60")
SAMPLE_SIZE = 20000
SAMPLE_VERSION = 0x000100


def sample_plain(n):
    s, out = 0x12345678, bytearray()
    while len(out) < n:
        s ^= (s << 13) & 0xFFFFFFFF
        s ^= s >> 17
        s ^= (s << 5) & 0xFFFFFFFF
        if s % 3 == 0 and len(out) > 64:
            lim = min(len(out), 4000)
            d, length = 1 + (s >> 8) % lim, 3 + (s >> 20) % 40
            for _ in range(length):
                if len(out) >= n:
                    break
                out.append(out[len(out) - d])
        else:
            out.append(((s >> 13) & 0x3F) | 0x20)
    return bytes(out)


def c_array(name, data):
    rows = [", ".join(f"0x{b:02x}" for b in data[i:i + 16]) for i in range(0, len(data), 16)]
    return f"static const uint8_t {name}[{len(data)}] = {{\n    " + ",\n    ".join(rows) + "\n};\n"


def main():
    plain = sample_plain(SAMPLE_SIZE)
    image = sign_image.make_image(plain, SAMPLE_VERSION, TEST_SEED)
    assert sign_image.unpack_binary(image) == plain
    out = ["/* Generated by make_fw_fixtures.py: do not edit.",
           " * SPDX-License-Identifier: AGPL-3.0-or-later */",
           "#include <stdint.h>", "",
           f"#define FIX_SAMPLE_SIZE {SAMPLE_SIZE}u",
           f"#define FIX_SAMPLE_VERSION 0x{SAMPLE_VERSION:06x}u", "",
           c_array("FIX_TEST_PUB", sign_image.ed25519_public(TEST_SEED)),
           c_array("FIX_SAMPLE_IMAGE", image)]
    (HERE / "fw_fixtures.h").write_text("\n".join(out))
    print(f"fw_fixtures.h: {len(plain)} -> {len(image) - sign_image.HDR_SIZE} bytes")


if __name__ == "__main__":
    main()
